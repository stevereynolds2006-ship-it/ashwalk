export const LEVELS: readonly Level[] = [SHORE, LATCH, GALE, CHOIR, GEAR, ROOF, ANTLER, MOON, MIRROR, TUNNEL];

export function previousFog(id: string): string | null {
  const index = LEVELS.findIndex((level) => level.id === id);
  if (index <= 0) return null;
  return LEVELS[index - 1]!.id;
}

/** Try build. Set true to open every fog. */
export const TRY_ALL = false;
/** Lets the tunnel be played before December 1. */
export const TRY_TUNNEL = true;

export function fogReleased(id: string, now = new Date()) {
  if (TRY_ALL) return true;
  if (id === "tunnel" && TRY_TUNNEL) return true;
  if (id === "moon") return now >= new Date(2026, 9, 1);
  if (id === "mirror") return now >= new Date(2026, 10, 1);
  if (id === "tunnel") return now >= new Date(2026, 11, 1);
  return true;
}

export function fogHeld(_id: string) {
  return false;
}
export function demoLocked(_id: string) {
  return false;
}

export function fogUnlocked(id: string, cleared: ReadonlySet<string>) {
  const prev = previousFog(id);
  return prev == null || cleared.has(prev);
}

export function getLevel(id: string): Level {
  return LEVELS.find((level) => level.id === id) ?? SHORE;
}
