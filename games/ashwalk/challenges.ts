export const LEVELS: readonly Level[] = [SHORE, LATCH, GALE, CHOIR, GEAR, ROOF, ANTLER];

export function previousFog(id: string): string | null {
  const index = LEVELS.findIndex((level) => level.id === id);
  if (index <= 0) return null;
  return LEVELS[index - 1]!.id;
}

export function fogUnlocked(id: string, cleared: ReadonlySet<string>) {
  const prev = previousFog(id);
  return prev == null || cleared.has(prev);
}

export function getLevel(id: string): Level {
  return LEVELS.find((level) => level.id === id) ?? SHORE;
}
